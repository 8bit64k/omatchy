# API routes
# ---------------------------------------------------------------------------

@router.get("/status")
async def omatchy_status():
    """Return the current Omarchy theme mapped to Hermes dashboard format.

    If Omarchy is not installed or no theme is active, returns a fallback
    dark theme so the dashboard stays usable.
    """
    theme_name, colors = get_current_omarchy_theme()
    font = get_current_font()

    if colors is None:
        # Omarchy not installed or theme not found — return a safe fallback
        return {
            "omarchyTheme": theme_name,
            "installed": False,
            "palette": {
                "background": {"hex": "#0a0a0a", "alpha": 1.0},
                "midground": {"hex": "#888888", "alpha": 1.0},
                "foreground": {"hex": "#ffffff", "alpha": 0.0},
                "warmGlow": "rgba(128, 128, 128, 0.22)",
                "noiseOpacity": 0.8,
            },
            "typography": {
                "fontSans": 'system-ui, -apple-system, "Segoe UI", Roboto, sans-serif',
                "fontMono": 'ui-monospace, "SF Mono", "Cascadia Mono", Menlo, Consolas, monospace',
                "baseSize": "15px",
                "lineHeight": "1.55",
                "letterSpacing": "0",
            },
            "layout": {"radius": "0.5rem", "density": "comfortable"},
            "layoutVariant": "standard",
            "colorOverrides": {
                "primary": "#7aa2f7",
                "primaryForeground": "#0a0a0a",
                "accent": "#7aa2f7",
                "ring": "#7aa2f7",
                "border": "rgba(122, 162, 247, 0.18)",
                "destructive": "#ef4444",
                "success": "#22c55e",
                "warning": "#f59e0b",
            },
        }

    result = map_omarchy_to_hermes(colors, font, theme_name)
    result["installed"] = True
    return result


@router.get("/hello")
async def omatchy_hello():
    return {"message": "Omatchy bridge is alive", "plugin": "omatchy", "version": "1.0.0"}
